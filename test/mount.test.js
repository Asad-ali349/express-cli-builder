const test = require('node:test');
const assert = require('node:assert/strict');
const { makeProject, captureLogs, assertValidEsm, assertValidCjs, read } = require('./helpers');
const { addRouteToSource } = require('../lib/mount');
const { buildAppFile } = require('../lib/init');
const createRoute = require('../commands/createRoute');
const createResource = require('../commands/createResource');

const esm = { moduleType: 'esm', importExt: '.js' };
const ts = { moduleType: 'ts', importExt: '' };
const cjs = { moduleType: 'cjs', importExt: '' };
const esmPkg = { type: 'module', dependencies: { mongoose: '^9.0.0' } };

test('route is imported and mounted in the app generated by init', () => {
  const app = buildAppFile({ isTs: false, database: 'MongoDB' });
  const updated = addRouteToSource(app, 'user', esm);

  assertValidEsm(updated);
  const lines = updated.split('\n');
  const importAt = lines.indexOf("import userRoutes from './routes/user.routes.js';");
  const useAt = lines.indexOf("app.use('/user', userRoutes);");
  const jsonAt = lines.indexOf('app.use(express.json());');
  const portAt = lines.findIndex((line) => line.startsWith('const PORT'));

  const notFoundAt = lines.indexOf('app.use(notFound);');

  assert.equal(importAt, lines.indexOf("import { errorHandler, notFound } from './middlewares/error.middleware.js';") + 1);
  assert.ok(useAt > jsonAt, 'route must come after the body parser');
  assert.ok(useAt < notFoundAt, 'route must come before the 404 handler');
  assert.ok(useAt < portAt, 'route must come before the server starts');
  assert.match(lines[useAt + 2], /^\/\/ Keep these last/, 'the comment stays with the handlers it describes');
  assert.equal(lines[useAt - 1], '');
  assert.equal(lines[useAt + 1], '');
});

test('TypeScript apps get an extension-less import', () => {
  const updated = addRouteToSource(buildAppFile({ isTs: true, database: null }), 'user-profile', ts);
  assert.match(updated, /^import userProfileRoutes from '\.\/routes\/user-profile\.routes';$/m);
  assert.match(updated, /^app\.use\('\/user-profile', userProfileRoutes\);$/m);
});

test('several routes are grouped together and mounting is idempotent', () => {
  let app = buildAppFile({ isTs: false, database: null });
  app = addRouteToSource(app, 'user', esm);
  app = addRouteToSource(app, 'product', esm);

  assert.match(app, /app\.use\('\/user', userRoutes\);\napp\.use\('\/product', productRoutes\);\n\n\/\/ Keep these last[^\n]*\napp\.use\(notFound\);/);
  assert.equal(addRouteToSource(app, 'user', esm), app);
  assertValidEsm(app);
});

test('CommonJS apps get a require and are mounted after the last app.use', () => {
  const app = [
    "const express = require('express');",
    '',
    'const app = express();',
    'app.use(express.json());',
    '',
    'module.exports = app;',
    '',
  ].join('\n');
  const updated = addRouteToSource(app, 'user', cjs);

  assertValidCjs(updated);
  assert.match(updated, /const express = require\('express'\);\nconst userRoutes = require\('\.\/routes\/user\.routes'\);/);
  assert.match(updated, /app\.use\(express\.json\(\)\);\n\napp\.use\('\/user', userRoutes\);\n\nmodule\.exports = app;/);
});

test('files that do not look like an Express app are left alone', () => {
  assert.equal(addRouteToSource('console.log("hello");\n', 'user', esm), null);
  assert.equal(addRouteToSource("import express from 'express';\nexport const app = express();\n", 'user', esm), null);
});

test('Windows line endings are preserved', () => {
  const app = buildAppFile({ isTs: false, database: null }).replace(/\n/g, '\r\n');
  const updated = addRouteToSource(app, 'user', esm);
  assert.ok(!/[^\r]\n/.test(updated), 'no bare \\n should be introduced');
});

test('create:resource mounts the route in the app file', async (t) => {
  const logs = captureLogs(t);
  const cwd = makeProject(t, { 'package.json': esmPkg, 'src/app.js': buildAppFile({ isTs: false, database: 'MongoDB' }) });

  await createResource('user', { cwd, install: false });

  const app = read(cwd, 'src/app.js');
  assert.match(app, /import userRoutes from '\.\/routes\/user\.routes\.js';/);
  assert.match(app, /app\.use\('\/user', userRoutes\);/);
  assert.ok(logs.some((line) => /Mounted route at \/user in src\/app\.js/.test(line)));
});

test('--no-mount leaves the app file untouched and prints instructions', async (t) => {
  const logs = captureLogs(t);
  const original = buildAppFile({ isTs: false, database: null });
  const cwd = makeProject(t, { 'package.json': esmPkg, 'app.js': original });

  await createRoute('user', { cwd, mount: false });

  assert.equal(read(cwd, 'app.js'), original);
  assert.ok(logs.some((line) => /Mount the route in your app file/.test(line)));
});

test('instructions are printed when there is no app file or it cannot be edited safely', async (t) => {
  const logs = captureLogs(t);
  const noApp = makeProject(t, { 'package.json': esmPkg });
  const oddApp = makeProject(t, { 'package.json': esmPkg, 'app.js': 'export default {};\n' });

  await createRoute('user', { cwd: noApp });
  await createRoute('user', { cwd: oddApp });

  assert.equal(logs.filter((line) => /Mount the route in your app file/.test(line)).length, 2);
  assert.equal(read(oddApp, 'app.js'), 'export default {};\n');
});

test('re-creating a route with --force does not mount it twice', async (t) => {
  captureLogs(t);
  const cwd = makeProject(t, { 'package.json': esmPkg, 'app.js': buildAppFile({ isTs: false, database: null }) });

  await createRoute('user', { cwd });
  await createRoute('user', { cwd, force: true });

  assert.equal(read(cwd, 'app.js').match(/app\.use\('\/user'/g).length, 1);
});
